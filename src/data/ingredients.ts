export function slugify(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/œ/g, 'oe')
    .replace(/[’']/g, '-')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function parse(cat: CategoryDef, line: string): Ingredient {
  const [name, emoji, img, flagStr = '', nutri = '', syn = ''] = line.split(';');
  const flags = `${cat.flags} ${flagStr}`.split(/\s+/).filter(Boolean);
  const has = (f: string) => flags.includes(f);
  const unit = flags.find((f) => /^u\d+$/.test(f));
  const parts = nutri.split('/').map(Number);
  const nutrition = parts.length === 4 && parts.every((n) => !Number.isNaN(n))
    ? N(parts[0], parts[1], parts[2], parts[3])
    : cat.nutrition;
  const meat = has('m');
  const fish = has('f');
  const animal = has('a') || has('l') || meat || fish;
  return {
    id: slugify(name),
    name,
    synonyms: syn.split(',').map((s) => s.trim()).filter(Boolean),
    category: cat.id,
    emoji: emoji || cat.emoji,
    image: img ? `https://www.themealdb.com/images/ingredients/${encodeURIComponent(img)}-small.png` : undefined,
    isPantryDefault: has('P'),
    unitWeight: unit ? Number(unit.slice(1)) : undefined,
    diet: {
      vegetarian: !meat && !fish,
      vegan: !animal,
      glutenFree: !has('g'),
      lactoseFree: !has('l'),
      pork: has('p'),
    },
    nutritionPer100g: nutrition,
  };
}

